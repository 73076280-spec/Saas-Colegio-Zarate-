export {}
function login(role: string) {
  cy.intercept('POST', '/api/v1/auth/login').as('centerLogin')
  cy.intercept('GET', '/api/v1/auth/me').as('initialSession')
  cy.visit('/login')
  cy.wait('@initialSession').its('response.statusCode').should('eq', 401)
  cy.get('input[name="email"]').type(role + '@zarate.test')
  cy.get('input[name="password"]').type('ZarateDemo2026!', { log: false })
  cy.contains('button', 'Ingresar').click()
  cy.wait('@centerLogin').its('response.statusCode').should('eq', 200)
  cy.location('pathname', { timeout: 15000 }).should('eq', '/app')
}
describe('Centro de Matrículas: navegación y permisos', () => {
  it('admin consulta indicadores reales por año y abre formulario historial y cupos sin escribir datos', () => {
    login('administrator')
    cy.contains('nav a', 'Centro de Matrículas').click()
    cy.get('[data-testid="enrollment-count-0"]', { timeout: 15000 }).should('be.visible')
    cy.get('select[aria-label="Año de matrículas"] option').filter('[value!=""]').first().then(option => {
      const year = String(option.val())
      cy.intercept('GET', '/api/v1/enrollments?*').as('yearCounts')
      cy.get('select[aria-label="Año de matrículas"]').select(year)
      cy.wait('@yearCounts').its('request.url').should('include', 'academic_year_id=' + year)
      cy.request({url: '/api/v1/enrollments?per_page=1&academic_year_id=' + year, headers: { Origin: 'http://localhost:5173', Accept: 'application/json' }}).then(response => {
        cy.get('[data-testid="enrollment-count-0"]').should('have.text', String(response.body.meta.total))
      })
    })
    cy.get('nav[aria-label="Navegación de Matrículas"] a[href$="/new"]').click()
    cy.get('select[name="student_id"]', { timeout: 15000 }).should('exist')
    cy.contains('button', 'Cerrar formulario').click()
    cy.get('nav[aria-label="Navegación de Matrículas"] a[href$="/history"]').click()
    cy.contains('h1', 'Historial de matrículas').should('be.visible')
    cy.contains('button', 'Nueva matrícula').should('not.exist')
    cy.contains('button', 'Detalle', { timeout: 15000 }).first().click()
    cy.get('[data-testid="enrollment-detail"]', { timeout: 15000 }).should('contain', 'Historial')
    cy.get('[data-testid="enrollment-detail"]').contains('button', 'Editar matrícula').should('not.exist')
    cy.get('nav[aria-label="Navegación de Matrículas"] a[href$="/capacity"]').click()
    cy.contains('h1', 'Consulta de cupos').should('be.visible')
    cy.get('select[name="capacity_year"] option').should('have.length.greaterThan', 1)
    cy.get('select[name="capacity_year"] option').eq(1).then(o => cy.get('select[name="capacity_year"]').select(String(o.val())))
    cy.get('select[name="capacity_grade"]', {timeout:15000}).should('exist')
    cy.get('select[name="capacity_grade"] option').should('have.length.greaterThan', 1)
    cy.intercept('GET', '/api/v1/enrollment-options?kind=sections*').as('sectionCapacity')
    cy.get('select[name="capacity_grade"] option').eq(1).then(o => cy.get('select[name="capacity_grade"]').select(String(o.val())))
    cy.wait('@sectionCapacity').its('response.statusCode').should('eq', 200)
    cy.contains('caption', 'Cupos por sección').should('be.visible')
    cy.viewport(390, 844)
    cy.document().then(d => expect(d.documentElement.scrollWidth).to.be.at.most(d.documentElement.clientWidth))
    cy.contains('a', 'Volver a Gestión Institucional').click()
    cy.location('pathname').should('eq', '/app')
  })
  it('estudiante y apoderado consultan su alcance y no acceden a creación ni cupos', () => {
    for (const role of ['student', 'guardian']) {
      login(role)
      cy.visit('/app/enrollments')
      cy.get('[data-testid="enrollment-count-0"]', { timeout: 15000 }).should('be.visible')
      cy.get('nav[aria-label="Navegación de Matrículas"] a[href$="/new"]').should('not.exist')
      cy.get('nav[aria-label="Navegación de Matrículas"] a[href$="/list"]').click()
      cy.contains('h1', 'Mi matrícula').should('be.visible')
      cy.visit('/app/enrollments/new')
      cy.contains('No tienes permiso para acceder', { timeout: 15000 }).should('be.visible')
      cy.visit('/app/enrollments/capacity')
      cy.contains('No tienes permiso para consultar cupos', { timeout: 15000 }).should('be.visible')
      cy.intercept('POST', '/api/v1/auth/logout').as('centerLogout')
      cy.contains('button', 'Cerrar sesión').click()
      cy.wait('@centerLogout')
    }
  })
  it('docente no accede al centro y mantiene acceso al Aula Virtual', () => {
    login('teacher')
    cy.contains('nav a', 'Centro de Matrículas').should('not.exist')
    cy.visit('/app/enrollments')
    cy.contains('No tienes permiso para acceder al Centro de Matrículas', { timeout: 15000 }).should('be.visible')
    cy.contains('a', 'Ir al Aula Virtual').click()
    cy.location('pathname').should('eq', '/virtual')
    cy.get('nav[aria-label="Navegación del Aula Virtual"]').should('be.visible')
    cy.contains('a', 'Volver a Gestión Institucional').click()
    cy.location('pathname').should('eq', '/app')
  })
})
