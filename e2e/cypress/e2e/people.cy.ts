function signIn(role = 'administrator') {
  cy.intercept('POST','/api/v1/auth/login').as('loginPeople')
  cy.visit('/login')
  cy.get('input[name="email"]').type(role+'@zarate.test')
  cy.get('input[name="password"]').type('ZarateDemo2026!', { log:false })
  cy.contains('button','Ingresar').click()
  cy.wait('@loginPeople').its('response.statusCode').should('eq',200)
  cy.location('pathname').should('eq','/app')
}
function openPeople(title: string) {
  cy.contains('nav a','Personas').click()
  cy.contains('a',title).click()
  cy.contains('h1',title).should('be.visible')
}
function account(suffix: string, label: string) {
  cy.get('input[name="first_name"]').type('E2E '+label)
  cy.get('input[name="last_name"]').type(suffix)
  cy.get('input[name="email"]').type(label.toLowerCase()+suffix+'@example.test')
  cy.get('input[name="password"]').type('InitialPass123!',{log:false})
  cy.get('select[name="document_type"]').select('PASSPORT')
  cy.get('input[name="document_number"]').type('E2E-'+label.toUpperCase()+'-'+suffix)
}
function findPerson(search: string) {
  cy.intercept('GET','/api/v1/*?*search=*').as('findPerson')
  cy.get('#people-search').clear().type(search)
  cy.contains('button','Buscar').click()
  cy.wait('@findPerson')
}
describe('Sprint 3: personas y relaciones reales', () => {
  it('crea consulta edita estudiantes y valida documentos y filtros', () => {
    const suffix=Date.now().toString()
    signIn()
    openPeople('Estudiantes')
    cy.contains('button','Nuevo estudiante').click()
    cy.get('input[name="first_name"]').then(input => expect((input[0] as HTMLInputElement).checkValidity()).to.eq(false))
    account(suffix,'Estudiante')
    cy.get('input[name="student_code"]').type('E2E-STU-'+suffix)
    cy.get('input[name="document_number"]').clear().type('DEMO-STU-DOC-01')
    cy.intercept('POST','/api/v1/students').as('createStudent')
    cy.contains('button','Guardar persona').click()
    cy.wait('@createStudent').its('response.statusCode').should('eq',422)
    cy.get('[role="alert"]').should('contain','Ya existe')
    cy.get('input[name="document_number"]').clear().type('E2E-STU-DOC-'+suffix)
    cy.contains('button','Guardar persona').click()
    cy.wait('@createStudent').its('response.statusCode').should('eq',201)
    findPerson('E2E-STU-'+suffix)
    cy.contains('tr',suffix).within(() => cy.contains('button','Detalle').click())
    cy.get('[data-testid="person-detail"]').should('contain','E2E Estudiante').and('contain','E2E-STU-DOC-'+suffix)
    cy.get('table').last().contains('tr',suffix).within(() => cy.contains('button','Editar').click())
    cy.get('input[name="address"]').type('Dirección ficticia E2E')
    cy.intercept('PATCH','/api/v1/students/*').as('updateStudent')
    cy.contains('button','Guardar persona').click()
    cy.wait('@updateStudent').its('response.statusCode').should('eq',200)
    cy.contains('tr',suffix).within(() => cy.contains('button','Detalle').click())
    cy.get('[data-testid="person-detail"]').should('contain','Dirección ficticia E2E')
    cy.contains('label','Filtrar estado').find('select').select('ACTIVE')
    cy.contains('tr',suffix).should('exist')
    cy.viewport(390,844)
    cy.document().then(document => expect(document.documentElement.scrollWidth).to.be.at.most(document.documentElement.clientWidth))
  })
  it('crea y consulta un docente sin asignaciones académicas', () => {
    const suffix=Date.now().toString()
    signIn()
    openPeople('Docentes')
    cy.contains('button','Nuevo docente').click()
    account(suffix,'Docente')
    cy.get('input[name="teacher_code"]').type('E2E-TCH-'+suffix)
    cy.get('input[name="specialty"]').type('Especialidad ficticia E2E')
    cy.get('input[name="hire_date"]').type('2026-03-01')
    cy.intercept('POST','/api/v1/teachers').as('createTeacher')
    cy.contains('button','Guardar persona').click()
    cy.wait('@createTeacher').its('response.statusCode').should('eq',201)
    findPerson('E2E-TCH-'+suffix)
    cy.contains('tr',suffix).should('contain','Especialidad ficticia E2E').within(() => cy.contains('button','Detalle').click())
    cy.get('[data-testid="person-detail"]').should('contain','2026-03-01')
    cy.contains('Cursos asignados').should('not.exist')
  })
  it('crea un apoderado y un estudiante aislados y gestiona su relación principal', () => {
    const suffix=Date.now().toString()
    signIn()
    openPeople('Padres / Apoderados')
    cy.contains('button','Nuevo apoderado').click()
    account(suffix,'Apoderado')
    cy.get('input[name="occupation"]').type('Ocupación ficticia')
    cy.intercept('POST','/api/v1/guardians').as('createGuardian')
    cy.contains('button','Guardar persona').click()
    cy.wait('@createGuardian').its('response.statusCode').should('eq',201)
    openPeople('Estudiantes')
    cy.contains('button','Nuevo estudiante').click()
    account(suffix,'Familiar')
    cy.get('input[name="student_code"]').type('E2E-FAM-'+suffix)
    cy.intercept('POST','/api/v1/students').as('createFamilyStudent')
    cy.contains('button','Guardar persona').click()
    cy.wait('@createFamilyStudent').its('response.statusCode').should('eq',201)
    findPerson('E2E-FAM-'+suffix)
    cy.contains('tr',suffix).within(() => cy.contains('button','Detalle').click())
    cy.contains('button','Asociar apoderado').click()
    cy.get('input[aria-label="Buscar apoderado"]').type(suffix)
    cy.contains('select[name="guardian_id"] option', 'E2E Apoderado', { timeout: 10000 }).then(option => cy.get('select[name="guardian_id"]').select(option.val() as string))
    cy.get('select[name="relationship"]').select('GUARDIAN')
    cy.get('input[name="can_pick_up"]').check()
    cy.get('input[name="receives_notifications"]').check()
    cy.intercept('POST','/api/v1/students/*/guardians').as('relate')
    cy.contains('button','Guardar relación').click()
    cy.wait('@relate').its('response.statusCode').should('eq',201)
    cy.get('[data-testid="person-detail"]').contains('tr','E2E Apoderado').within(() => cy.contains('button','Editar relación').click())
    cy.get('input[name="is_primary"]').check()
    cy.intercept('PATCH','/api/v1/students/*/guardians/*').as('primary')
    cy.contains('button','Guardar relación').click()
    cy.wait('@primary').its('response.body.data.is_primary').should('eq',true)
    cy.get('[data-testid="person-detail"]').contains('tr','E2E Apoderado').should('contain','Sí')
    openPeople('Padres / Apoderados')
    findPerson(suffix)
    cy.contains('tr',suffix).within(() => cy.contains('button','Detalle').click())
    cy.get('[data-testid="person-detail"]').should('contain','E2E Familiar')
    cy.viewport(390,844)
    cy.document().then(document => expect(document.documentElement.scrollWidth).to.be.at.most(document.documentElement.clientWidth))
  })
  it('muestra al estudiante su perfil propio sin administración de personas', () => {
    signIn('student')
    cy.contains('nav a','Personas').should('not.exist')
    cy.intercept('GET','/api/v1/profile/people').as('studentProfile')
    cy.contains('a','Mi perfil').click()
    cy.wait('@studentProfile').its('response.statusCode').should('eq',200)
    cy.contains('h2','Mi perfil de estudiante', { timeout: 15000 }).should('be.visible')
    cy.contains('DEMO-STU-01').should('be.visible')
    cy.visit('/app/people/students')
    cy.get('[role="alert"]').should('contain','No tienes permiso')
  })
  it('muestra al apoderado únicamente su perfil y sus relaciones demo', () => {
    signIn('guardian')
    cy.intercept('GET','/api/v1/profile/people').as('guardianProfile')
    cy.intercept('GET','/api/v1/profile/family?*').as('guardianFamily')
    cy.contains('a','Mi perfil').click()
    cy.wait('@guardianProfile').its('response.statusCode').should('eq',200)
    cy.contains('h2','Mi perfil de apoderado', { timeout: 15000 }).should('be.visible')
    cy.wait('@guardianFamily').its('response.statusCode').should('eq',200)
    cy.contains('h2','Mis relaciones familiares', { timeout: 15000 }).should('be.visible')
    cy.contains('td','Demo STUDENT').should('be.visible')
    cy.contains('td','Estudiante Ficticio Dos').should('be.visible')
    cy.contains('button','Asociar apoderado').should('not.exist')
  })
})
