function academicLogin(role = 'administrator') {
  cy.intercept('POST', '/api/v1/auth/login').as('signIn')
  cy.visit('/login')
  cy.get('input[name="email"]', { timeout: 15000 }).should('be.visible').type(role+'@zarate.test')
  cy.get('input[name="password"]').type('ZarateDemo2026!', { log: false })
  cy.contains('button', 'Ingresar').click()
  cy.wait('@signIn').its('response.statusCode').should('eq', 200)
  cy.location('pathname').should('eq','/app')
}
function openCatalog(label: string) {
  const paths: Record<string, string> = { 'Años académicos': 'academic-years', 'Niveles educativos': 'education-levels', Asignaturas: 'subjects' }
  const alias = 'catalog-' + paths[label]
  cy.intercept('GET', '/api/v1/' + paths[label] + '?*').as(alias)
  cy.contains('nav a', 'Gestión Académica').click()
  cy.location('pathname').should('eq', '/app/academic')
  cy.get('a[href="/app/academic/' + paths[label] + '"]', { timeout: 15000 }).should('contain', label).click()
  cy.wait(`@${alias}`).its('response.statusCode').should('eq', 200)
  cy.contains('h1', label, { timeout: 15000 }).should('be.visible')
}
function searchCatalog(value: string) {
  cy.intercept('GET', '/api/v1/*?*search=*').as('searchCatalog')
  cy.get('#catalog-search').clear().type(value)
  cy.contains('button','Buscar').click()
  cy.wait('@searchCatalog')
}
describe('Sprint 2: estructura académica con Laravel real', () => {
  it('consulta año y periodos y navega niveles, grados y secciones en móvil', () => {
    academicLogin()
    openCatalog('Años académicos')
    searchCatalog('2026')
    cy.intercept('GET', '/api/v1/academic-years/*').as('yearDetail')
    cy.contains('tr', '2026', { timeout: 15000 }).within(() => cy.contains('button','Detalle').click())
    cy.wait('@yearDetail').its('response.statusCode').should('eq', 200)
    cy.intercept('GET','/api/v1/academic-periods?*').as('loadPeriods')
    cy.get('section[aria-label="Detalle"]').within(() => {
      cy.contains('Bimestre 1').should('be.visible')
      cy.contains('Bimestre 4').should('be.visible')
      cy.contains('a','Ver periodos').click()
    })
    cy.contains('h1','Periodos').should('be.visible')
    cy.wait('@loadPeriods').its('response.statusCode').should('eq',200)
    cy.get('tbody tr',{timeout:15000}).should('have.length',4)
    openCatalog('Niveles educativos')
    searchCatalog('Primaria')
    cy.intercept('GET','/api/v1/grade-levels?*').as('loadGrades')
    cy.contains('tr','Primaria').within(() => cy.contains('a','Ver grados').click())
    cy.contains('h1','Grados').should('be.visible')
    cy.wait('@loadGrades').its('response.statusCode').should('eq',200)
    cy.get('tbody tr',{timeout:15000}).should('have.length',6)
    cy.intercept('GET','/api/v1/sections?*').as('loadSections')
    cy.contains('tr','1.º').within(() => cy.contains('a','Ver secciones').click())
    cy.wait('@loadSections').its('response.statusCode').should('eq',200)
    cy.contains('h1','Secciones').should('be.visible')
    cy.get('tbody tr', { timeout: 10000 }).should('have.length',2)
    cy.viewport(390,844)
    cy.contains('h1','Secciones').should('be.visible')
    cy.document().then(document => expect(document.documentElement.scrollWidth).to.be.at.most(document.documentElement.clientWidth))
  })

  it('valida crea edita y desactiva una asignatura de prueba conservando su historial', () => {
    const suffix = Date.now().toString()
    const name = 'E2E Asignatura '+suffix
    academicLogin()
    openCatalog('Asignaturas')
    cy.contains('button','Crear asignatura').click()
    cy.get('input[name="name"]').then(input => expect((input[0] as HTMLInputElement).checkValidity()).to.eq(false))
    cy.get('input[name="name"]').type(name)
    cy.get('input[name="code"]').type('MAT-001')
    cy.intercept('POST','/api/v1/subjects').as('createSubject')
    cy.contains('button','Guardar').click()
    cy.wait('@createSubject').its('response.statusCode').should('eq',422)
    cy.get('[role="alert"]').should('contain','Ya existe')
    cy.get('input[name="code"]').clear().type('E2E-'+suffix)
    cy.contains('button','Guardar').click()
    cy.wait('@createSubject').its('response.statusCode').should('eq',201)
    cy.contains('Registro guardado.').should('be.visible')
    searchCatalog(name)
    cy.contains('tr',name).within(() => cy.contains('button','Editar').click())
    cy.get('textarea[name="description"]').clear().type('Editada por Cypress; dato de prueba.')
    cy.intercept('PATCH','/api/v1/subjects/*').as('editSubject')
    cy.contains('button','Guardar').click()
    cy.wait('@editSubject').its('response.statusCode').should('eq',200)
    cy.contains('td','Editada por Cypress').should('be.visible')
    cy.on('window:confirm', () => true)
    cy.intercept('POST','/api/v1/subjects/*/disable').as('disableSubject')
    cy.contains('tr',name).within(() => cy.contains('button','Desactivar').click())
    cy.wait('@disableSubject').its('response.statusCode').should('eq',200)
    cy.contains('tr',name).should('contain','Inactivo')
    cy.contains('label','Filtrar estado').find('select').select('INACTIVE')
    cy.contains('tr',name).should('exist')
  })

  it('valida fechas y cierra únicamente un año de prueba sin cambiar el actual', () => {
    const name = 'E2E Año '+Date.now()
    academicLogin()
    openCatalog('Años académicos')
    cy.contains('button','Crear año académico').click()
    cy.get('input[name="name"]').type(name)
    cy.get('input[name="start_date"]').type('2040-03-01')
    cy.get('input[name="end_date"]').type('2040-02-01')
    cy.intercept('POST','/api/v1/academic-years').as('createYear')
    cy.contains('button','Guardar').click()
    cy.wait('@createYear').its('response.statusCode').should('eq',422)
    cy.get('[role="alert"]').should('contain','posterior')
    cy.get('input[name="end_date"]').clear().type('2040-12-20')
    cy.contains('button','Guardar').click()
    cy.wait('@createYear').its('response.statusCode').should('eq',201)
    searchCatalog(name)
    cy.on('window:confirm', () => true)
    cy.intercept('POST','/api/v1/academic-years/*/close').as('closeYear')
    cy.contains('tr',name).within(() => cy.contains('button','Cerrar').click())
    cy.wait('@closeYear').its('response.statusCode').should('eq',200)
    cy.contains('tr',name).should('contain','Cerrado').within(() => cy.contains('button','Editar').should('not.exist'))
  })

  it('permite consulta académica docente sin controles de gestión', () => {
    academicLogin('teacher')
    openCatalog('Asignaturas')
    cy.get('tbody tr').should('have.length.greaterThan',0)
    cy.contains('button','Crear asignatura').should('not.exist')
    cy.contains('button','Editar').should('not.exist')
    cy.contains('button','Desactivar').should('not.exist')
    cy.getCookie('XSRF-TOKEN').then(cookie => {
      cy.request({ method:'POST',url:'/api/v1/subjects',headers:{Origin:'http://localhost:5173',Accept:'application/json','X-XSRF-TOKEN':decodeURIComponent(cookie!.value)},body:{},failOnStatusCode:false }).its('status').should('eq',403)
    })
    cy.viewport(390,844)
    cy.document().then(document => expect(document.documentElement.scrollWidth).to.be.at.most(document.documentElement.clientWidth))
  })
})
