beforeEach(()=>{
 cy.intercept('POST','/api/v1/auth/login').as('courseLogin')
 cy.intercept('POST','/api/v1/auth/logout').as('courseLogout')
 cy.intercept('GET','/api/v1/my/courses?*').as('myCourses')
 cy.intercept('GET','/api/v1/courses/*/students?*').as('courseRoster')
 cy.intercept('GET','/api/v1/courses/*').as('courseDetail')
})
function courseLogin(role='administrator'){
 cy.visit('/login')
 cy.get('input[name="email"]').type(role+'@zarate.test')
 cy.get('input[name="password"]').type('ZarateDemo2026!',{log:false})
 cy.contains('button','Ingresar').click()
 cy.wait('@courseLogin').its('response.statusCode').should('eq',200)
 cy.location('pathname',{timeout:15000}).should('eq','/app')
}
function courseRequest(path:string,body:object){
 return cy.getCookie('XSRF-TOKEN',{log:false}).then(c=>cy.request({method:'POST',url:'/api/v1/'+path,body,headers:{'X-XSRF-TOKEN':decodeURIComponent(c!.value),Origin:'http://localhost:5173',Accept:'application/json'},log:false})).then(r=>r.body.data)
}
function courseSelect(name:string,text:string){
 cy.contains('select[name="'+name+'"] option',text,{timeout:20000}).then(o=>cy.get('select[name="'+name+'"]').select(o.val() as string))
}
function courseStructure(suffix:string){
 cy.get('input[aria-label="Buscar Docente"]').type('Demo')
 courseSelect('teacher_id','Docente Demo')
 cy.get('input[aria-label="Buscar Asignatura"]').type('E2E S5 '+suffix)
 courseSelect('subject_id','E2E S5 '+suffix)
 cy.get('input[aria-label="Buscar Año académico"]').type('E2E S5 '+suffix)
 courseSelect('academic_year_id','E2E S5 '+suffix)
 courseSelect('grade_level_id','Grado S5')
 courseSelect('section_id','S5 A')
}
describe('Sprint 5: cursos y docencia',()=>{
 it('crea asignación y curso y controla activación cierre y responsive',()=>{
 const suffix=String(Date.now()),name='E2E Curso '+suffix
 courseLogin()
 courseRequest('academic-years',{name:'E2E S5 '+suffix,start_date:'2026-03-01',end_date:'2026-12-20',status:'ACTIVE'}).then(year=>{
 courseRequest('education-levels',{name:'Nivel S5 '+suffix,code:'S5-'+suffix,status:'ACTIVE'}).then(level=>{
 courseRequest('grade-levels',{education_level_id:level.id,name:'Grado S5',code:'G1',status:'ACTIVE'}).then(grade=>{
 courseRequest('sections',{academic_year_id:year.id,grade_level_id:grade.id,name:'S5 A',capacity:30,status:'ACTIVE'})
 })})})
 courseRequest('subjects',{name:'E2E S5 '+suffix,code:'S5-'+suffix,status:'ACTIVE'})
 cy.contains('nav a','Asignación docente').click()
 cy.contains('button','Crear asignación').click()
 courseStructure(suffix)
 cy.intercept('POST','/api/v1/teacher-assignments').as('newAssignment')
 cy.contains('button','Guardar asignación').click()
 cy.wait('@newAssignment').its('response.statusCode').should('eq',201)
 cy.get('[data-testid="teaching-detail"]',{timeout:15000}).should('contain','Asignación docente')
 cy.contains('nav a','Cursos').click()
 cy.contains('button','Crear curso').click()
 courseStructure(suffix)
 cy.get('input[name="name"]').type(name)
 cy.get('input[name="code"]').type('S5-'+suffix)
 cy.intercept('POST','/api/v1/courses').as('newCourse')
 cy.contains('button','Guardar curso').click()
 cy.wait('@newCourse').its('response.statusCode').should('eq',201)
 cy.on('window:confirm',()=>true)
 cy.intercept('POST','/api/v1/courses/*/activate').as('activateCourse')
 cy.get('[data-testid="teaching-detail"]',{timeout:15000}).within(()=>cy.contains('button','Activar curso').click())
 cy.wait('@activateCourse').its('response.statusCode').should('eq',200)
 cy.get('[data-testid="teaching-detail"]').should('contain','Activo')
 cy.intercept('POST','/api/v1/courses/*/close').as('closeCourse')
 cy.contains('button','Cerrar curso').click()
 cy.wait('@closeCourse').its('response.statusCode').should('eq',200)
 cy.get('[data-testid="teaching-detail"]').should('contain','Cerrado')
 cy.viewport(390,844)
 cy.document().then(d=>expect(d.documentElement.scrollWidth).to.be.at.most(d.documentElement.clientWidth))
 })
 it('muestra al docente sus cursos y roster aprobado sin controles administrativos',()=>{
 courseLogin('teacher')
 cy.contains('nav a','Mis cursos').click()
 cy.wait('@myCourses').its('response.statusCode').should('eq',200)
 cy.contains('article','Comunicación — curso demo').should('be.visible')
 cy.contains('article','Ciencia y Tecnología — curso demo').should('be.visible')
 cy.contains('article','Inglés — curso demo').should('be.visible')
 cy.contains('article','Matemática — curso demo',{timeout:15000}).within(()=>cy.contains('button','Entrar al curso').click())
 cy.wait('@courseDetail')
 cy.location('pathname').should('match',/^\/app\/my-courses\/\d+$/)
 cy.wait('@courseRoster').its('response.statusCode').should('eq',200)
 cy.contains('td','DEMO-STU-01',{timeout:15000}).should('be.visible')
 cy.contains('td','DEMO-STU-03').should('be.visible')
 cy.contains('td','DEMO-STU-04').should('be.visible')
 cy.contains('td','DEMO-STU-02').should('not.exist')
 cy.contains('nav a','Mis cursos').click()
 cy.wait('@myCourses').its('response.statusCode').should('eq',200)
 cy.contains('article','Ciencia y Tecnología — curso demo').within(()=>cy.contains('button','Entrar al curso').click())
 cy.wait('@courseDetail')
 cy.wait('@courseRoster').its('response.statusCode').should('eq',200)
 cy.contains('td','DEMO-STU-05',{timeout:15000}).should('be.visible')
 cy.contains('td','DEMO-STU-06').should('be.visible')
 cy.contains('button[role="tab"]','Tareas').click()
 cy.contains('Actividad práctica: Ciencia y Tecnología (demo)',{timeout:15000}).should('be.visible')
 cy.contains('button[role="tab"]','Evaluaciones').click()
 cy.contains('Evaluación de Ciencia y Tecnología (demo)',{timeout:15000}).should('be.visible')
 cy.contains('button','Crear curso').should('not.exist')
 cy.contains('button','Activar curso').should('not.exist')
 cy.contains('Aula Virtual').should('be.visible')
 })
 it('permite al matriculado consultar su curso',()=>{
 courseLogin('student')
 cy.contains('nav a','Mis cursos').click()
 cy.wait('@myCourses').its('response.statusCode').should('eq',200)
 cy.contains('article','Matemática — curso demo',{timeout:15000}).within(()=>cy.contains('button','Entrar al curso').click())
 cy.wait('@courseDetail')
 cy.get('[data-testid="teaching-detail"]',{timeout:15000}).should('contain','Aula Virtual')
 cy.contains('Estudiantes matriculados').should('not.exist')
 cy.contains('button','Crear curso').should('not.exist')
 cy.viewport(390,844)
 cy.document().then(d=>expect(d.documentElement.scrollWidth).to.be.at.most(d.documentElement.clientWidth))
 cy.contains('button','Cerrar sesión').click()
 cy.wait('@courseLogout').its('response.statusCode').should('eq',204)
 cy.location('pathname',{timeout:15000}).should('eq','/login')
 })
 it('excluye al estudiante observado de cursos y gestión docente',()=>{
 courseLogin('student2')
 cy.contains('nav a','Mis cursos').click()
 cy.wait('@myCourses').its('response.body.data').should('have.length',0)
 cy.contains('No hay cursos o asignaciones disponibles',{timeout:15000}).should('be.visible')
 cy.visit('/app/teacher-assignments')
 cy.contains('No tienes permiso para acceder',{timeout:15000}).should('be.visible')
 })
})
