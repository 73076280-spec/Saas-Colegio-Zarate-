export {}

function visualLogin(role: string) {
  cy.intercept('POST', '/api/v1/auth/login').as('visualLogin')
  cy.intercept('GET', '/api/v1/dashboard*').as('visualDashboard')
  cy.visit('/login')
  cy.get('[name="email"]', { timeout: 15000 }).type(role + '@zarate.test')
  cy.get('[name="password"]').type('ZarateDemo2026!', { log: false })
  cy.contains('button', 'Ingresar').click()
  cy.wait('@visualLogin').its('response.statusCode').should('eq', 200)
  cy.wait('@visualDashboard').its('response.statusCode').should('eq', 200)
  cy.get('[data-testid="dashboard-data"]', { timeout: 15000 }).should('be.visible')
}

describe('Refresh visual institucional', () => {
  it('mantiene login claro y tema persistente en dashboard perfil y móvil', () => {
    cy.viewport(1200, 800)
    cy.visit('/login')
    cy.contains('h2', 'Iniciar sesión').should('be.visible')
    cy.get('.theme-toggle').should('not.exist')
    cy.document().then(doc => expect(doc.documentElement.scrollWidth).to.be.at.most(doc.documentElement.clientWidth))
    cy.screenshot('refresh-login', { capture: 'viewport' })
    visualLogin('administrator')
    cy.document().then(doc => expect(doc.documentElement.scrollWidth).to.be.at.most(doc.documentElement.clientWidth))
    cy.get('[data-theme]').then(shell => {
      if (shell.attr('data-theme') === 'dark') cy.get('.theme-toggle').click()
    })
    cy.screenshot('refresh-dashboard-light', { capture: 'viewport' })
    cy.get('.theme-toggle').click()
    cy.get('[data-theme]').should('have.attr', 'data-theme', 'dark')
    cy.reload()
    cy.get('[data-theme]', { timeout: 15000 }).should('have.attr', 'data-theme', 'dark')
    cy.get('[data-testid="dashboard-data"]', { timeout: 15000 }).should('be.visible')
    cy.screenshot('refresh-dashboard-dark', { capture: 'viewport' })
    cy.intercept('GET', '/api/v1/reports').as('visualReports')
    cy.contains('nav a', 'Reportes').click()
    cy.wait('@visualReports').its('response.statusCode').should('eq', 200)
    cy.get('select[name="report"]', { timeout: 15000 }).should('be.visible')
    cy.screenshot('refresh-reports-dark', { capture: 'viewport' })
    cy.get('[aria-label="Notificaciones"]').click()
    cy.get('#notification-popover').should('be.visible')
    cy.contains('button', 'Cerrar notificaciones').click()
    cy.contains('nav a', 'Mi perfil').click()
    cy.contains('h2', 'Datos de tu cuenta', { timeout: 15000 }).should('be.visible')
    cy.get('input[name="first_name"]').should('be.visible')
    cy.screenshot('refresh-profile-dark', { capture: 'viewport' })
    cy.viewport(390, 844)
    cy.get('.theme-toggle').should('be.visible')
    cy.document().then(doc => expect(doc.documentElement.scrollWidth).to.be.at.most(doc.documentElement.clientWidth))
    cy.screenshot('refresh-mobile-dark', { capture: 'viewport' })
    cy.get('.theme-toggle').click()
    cy.contains('button', 'Cerrar sesión').click()
    cy.location('pathname', { timeout: 15000 }).should('eq', '/login')
    cy.get('.theme-toggle').should('not.exist')
    cy.get('[data-theme="dark"]').should('not.exist')
    cy.document().then(doc => expect(doc.documentElement.scrollWidth).to.be.at.most(doc.documentElement.clientWidth))
    cy.screenshot('refresh-login-mobile', { capture: 'viewport' })
  })

  it('muestra ficha académica y vista previa de foto sin alterar la foto existente', () => {
    visualLogin('student')
    cy.intercept('GET', '/api/v1/profile/people').as('ownProfile')
    cy.intercept('GET', '/api/v1/students/*/enrollments?*').as('ownEnrollments')
    cy.contains('nav a', 'Mi perfil').click()
    cy.wait('@ownProfile').its('response.statusCode').should('eq', 200)
    cy.wait('@ownEnrollments').its('response.statusCode').should('eq', 200)
    cy.contains('h3', 'Matrículas recientes').should('be.visible')
    cy.get('input[name="photo"]').selectFile({ contents: Cypress.Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aS1cAAAAASUVORK5CYII=', 'base64'), fileName: 'preview.png', mimeType: 'image/png' }, { force: true })
    cy.get('section[aria-label="Foto de perfil"] img').should('have.attr', 'src').and('match', /^blob:/)
    cy.contains('button', 'Guardar foto').should('be.enabled')
    cy.contains('button', 'Cancelar foto').click()
    cy.get('section[aria-label="Foto de perfil"] img[src^="blob:"]').should('not.exist')
    cy.contains('nav a', 'Personas').should('not.exist')
  })
})
