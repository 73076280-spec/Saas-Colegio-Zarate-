function enrollmentSignIn(role='administrator') {
 cy.visit('/login')
 cy.get('input[name="email"]').type(role+'@zarate.test')
 cy.get('input[name="password"]').type('ZarateDemo2026!',{log:false})
 cy.contains('button','Ingresar').click()
 cy.wait('@enrollmentLogin').its('response.statusCode').should('eq',200)
 cy.location('pathname',{timeout:15000}).should('eq','/app')
}
function enrollmentRequest(path:string,body:object) {
 return cy.getCookie('XSRF-TOKEN',{log:false}).then(cookie=>cy.request({method:'POST',url:'/api/v1/'+path,body,headers:{'X-XSRF-TOKEN':decodeURIComponent(cookie!.value),'Accept':'application/json','Origin':'http://localhost:5173','Referer':'http://localhost:5173/'},log:false})).then(r=>r.body.data)
}
function enrollmentSelect(name:string,label:string) {
 cy.contains('select[name="'+name+'"] option',label,{timeout:15000}).then(o=>cy.get('select[name="'+name+'"]').select(o.val() as string))
}
function enrollmentSearch(code:string) {
 cy.get('input[aria-label="Buscar matrícula"]').clear().type(code)
 cy.contains('button','Buscar').click()
 cy.contains('tr',code,{timeout:15000}).within(()=>cy.contains('button','Detalle').click())
 cy.wait('@enrollmentDetail').its('response.statusCode').should('eq',200)
 cy.get('[data-testid="enrollment-detail"]',{timeout:15000}).should('contain',code)
}
