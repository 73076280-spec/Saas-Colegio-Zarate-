const apiHeaders = { Origin: 'http://localhost:5173', Accept: 'application/json' }
function virtualLogin(role: string) {
  cy.intercept('POST', '/api/v1/auth/login').as('virtualLogin')
  cy.visit('/login')
  cy.get('input[name="email"]').type(role + '@zarate.test')
  cy.get('input[name="password"]').type('ZarateDemo2026!', { log: false })
  cy.contains('button', 'Ingresar').click()
  cy.wait('@virtualLogin').its('response.statusCode').should('eq', 200)
  cy.location('pathname', { timeout: 15000 }).should('eq', '/app')
}
function enterVirtual() {
  cy.contains('a', /^Ir al Aula Virtual$/).click()
  cy.location('pathname').should('eq', '/virtual')
  cy.get('[data-testid="course-card"]', { timeout: 15000 }).should('exist')
}
describe('Aula Virtual independiente', () => {
  it('mantiene la sesión del estudiante y navega recursos reales en PC tablet y móvil', () => {
    virtualLogin('student')
    cy.request({ url: '/api/v1/auth/me', headers: apiHeaders }).then(before => {
      enterVirtual()
      for (const [width, height] of [[1280, 800], [768, 900], [390, 844]]) {
        cy.viewport(width, height)
        cy.document().then(d => expect(d.documentElement.scrollWidth).to.be.at.most(d.documentElement.clientWidth))
        cy.screenshot('virtual-student-' + width, { capture: 'viewport' })
      }
      cy.get('[data-testid="course-card"]').first().contains('a', 'Entrar al curso').click()
      cy.get('[data-testid="virtual-course"]', { timeout: 15000 }).should('be.visible')
      cy.contains('button', 'Nueva unidad').should('not.exist')
      cy.contains('Listado de estudiantes del curso').should('not.exist')
      cy.intercept('GET', '/api/v1/my/assignments*').as('personalTasks')
      cy.get('nav[aria-label="Navegación del Aula Virtual"] a[href="/virtual/assignments"]').click()
      cy.wait('@personalTasks').its('response.statusCode').should('eq', 200)
      cy.contains('a', 'Volver a Gestión Institucional').click()
      cy.location('pathname').should('eq', '/app')
      cy.request({ url: '/api/v1/auth/me', headers: apiHeaders }).its('body').should('deep.equal', before.body)
    })
  })
  it('ofrece al docente sus cursos y herramientas y conserva el acceso institucional', () => {
    virtualLogin('teacher')
    enterVirtual()
    cy.get('nav[aria-label="Navegación del Aula Virtual"] a[href="/virtual/materials"]').click()
    cy.intercept('GET', '/api/v1/my/courses?*').as('filteredCourses')
    cy.get('input[placeholder="Buscar"]').type('DEMO-MAT-2026')
    cy.contains('button', /^Buscar$/).click()
    cy.wait('@filteredCourses')
    cy.get('[data-testid="course-card"]', { timeout: 15000 }).first().contains('a', 'Entrar al curso').click()
    cy.get('[data-testid="virtual-course"]', { timeout: 15000 }).should('be.visible')
    cy.get('[role="tab"]').contains('Tareas').click()
    cy.location('pathname').should('match', /\/virtual\/courses\/\d+\/assignments$/)
    cy.contains('button', 'Crear tarea', { timeout: 15000 }).should('be.visible')
    cy.contains('summary', 'Listado de estudiantes del curso').click()
    cy.get('table', { timeout: 15000 }).should('be.visible')
    cy.screenshot('virtual-teacher-course', { capture: 'viewport' })
    cy.contains('a', 'Volver a Gestión Institucional').click()
    cy.contains('nav a', 'Mis cursos').click()
    cy.location('pathname').should('eq', '/app/my-courses')
    cy.get('[data-testid="course-card"]', { timeout: 15000 }).should('exist')
  })
  it('admite administración y rechaza roles ajenos y estudiantes sin matrícula aprobada', () => {
    virtualLogin('administrator')
    enterVirtual()
    cy.get('[data-testid="course-card"] a').first().invoke('attr', 'href').then(href => {
      const courseId = href!.split('/').pop()
      cy.clearCookies()
      virtualLogin('student2')
      cy.visit('/virtual/courses/' + courseId)
      cy.request({ url: '/api/v1/courses/' + courseId, headers: apiHeaders, failOnStatusCode: false }).its('status').should('eq', 404)
      cy.get('[data-testid="virtual-course"]').should('not.exist')
      cy.get('[role="alert"]', { timeout: 15000 }).should('be.visible')
    })
    cy.clearCookies()
    virtualLogin('treasury')
    cy.contains('a', /^Ir al Aula Virtual$/).should('not.exist')
    cy.visit('/virtual')
    cy.contains('No tienes permiso para acceder al Aula Virtual.', { timeout: 15000 }).should('be.visible')
  })
})
